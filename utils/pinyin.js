/**
 * 获取姓名的拼音首字母
 * @param {string} name - 姓名
 * @returns {string} - 拼音首字母（大写）
 */
function getPinyinInitial(name) {
  if (!name || name.length === 0) {
    return '#'
  }
  
  // 提取第一个字符（姓氏）
  const firstChar = name.charAt(0)
  
  // 如果是中文，查找映射表
  if (/[\u4e00-\u9fa5]/.test(firstChar)) {
    return pinyinMap[firstChar] || '#'
  }
  
  // 如果是英文字母，直接返回大写
  if (/[a-zA-Z]/.test(firstChar)) {
    return firstChar.toUpperCase()
  }
  
  // 如果是数字，返回数字
  if (/[0-9]/.test(firstChar)) {
    return firstChar
  }
  
  // 其他字符返回 #
  return '#'
}

/**
 * 对人物列表按姓氏首字母排序
 * @param {Array} figures - 人物列表
 * @returns {Array} - 排序后的人物列表
 */
function sortFiguresByInitial(figures) {
  return figures.sort((a, b) => {
    const initialA = getPinyinInitial(a.name)
    const initialB = getPinyinInitial(b.name)
    
    // 先按首字母排序
    if (initialA !== initialB) {
      // # 排在最后
      if (initialA === '#') return 1
      if (initialB === '#') return -1
      return initialA.localeCompare(initialB)
    }
    
    // 首字母相同，按姓名排序
    return a.name.localeCompare(b.name, 'zh-CN')
  })
}

